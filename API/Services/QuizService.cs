    public async Task<Question?> UpdateQuestion(int id, CreateQuestionRequest request)
    {
        var question = await _context.Questions
            .FirstOrDefaultAsync(q => q.Id == id);

        if (question == null)
            return null;

        var data = new QuestionData
        {
            Options = request.Options,
            CorrectAnswer = request.CorrectAnswer
        };

        question.Text = request.Text;
        question.Difficulty = request.Difficulty;
        question.Category = request.Category;
        question.Type = request.Type;

        question.Data = JsonSerializer.Serialize(data);

        await _context.SaveChangesAsync();

        return question;
    }

    public async Task<BugReport> CreateBugReport(
        int userId,
        CreateBugReportRequest request)
    {
        var user = await _context.Users.FindAsync(userId);

        if (user == null)
            throw new Exception("User not found");

        if (user.Role == Roles.Admin)
            throw new Exception("Admins cannot submit bug reports");

        var report = new BugReport
        {
            UserId = userId,
            Title = request.Title,
            Description = request.Description,
            Status = "Open",
            Severity = BugSeverities.Medium,
            CreatedAt = DateTime.UtcNow
        };

        _context.BugReports.Add(report);

        await _context.SaveChangesAsync();

        return report;
    }

