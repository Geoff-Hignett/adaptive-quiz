    public async Task<BugReport?> UpdateBug(
        int id, 
        UpdateBugRequest request)
    {
        var bug = await _context.BugReports
            .FirstOrDefaultAsync(x => x.Id == id);

        if (bug == null)
            return null;

        var allowed = new[]
        {
        "Open",
        "In Progress",
        "Resolved",
        "Closed"
    };

        if (!allowed.Contains(request.Status))
            throw new Exception("Invalid status");

        if (request.Severity != BugSeverities.Low &&
            request.Severity != BugSeverities.Medium &&
            request.Severity != BugSeverities.High &&
            request.Severity != BugSeverities.Critical)
        {
            throw new Exception("Invalid severity");
        }

        bug.Status = request.Status;
        bug.Severity = request.Severity;

        await _context.SaveChangesAsync();

        return bug;
    }

    public async Task<BugComment> AddBugComment(
        int bugId,
        int userId,
        CreateBugCommentRequest request)
    {
        var bug = await _context.BugReports
            .FirstOrDefaultAsync(x => x.Id == bugId);

        if (bug == null)
            throw new Exception("Bug not found");

        if (string.IsNullOrWhiteSpace(request.Comment))
            throw new Exception("Comment is required");

        var comment = new BugComment
        {
            BugReportId = bugId,
            UserId = userId,
            Comment = request.Comment.Trim(),
            CreatedAt = DateTime.UtcNow
        };

        _context.BugComments.Add(comment);

        await _context.SaveChangesAsync();

        return comment;
    }

