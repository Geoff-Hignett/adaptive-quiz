    public async Task<object> UpdateDisplayName(int userId, string displayName)
    {
        if (string.IsNullOrWhiteSpace(displayName))
            throw new Exception("Display name is required");

        displayName = displayName.Trim();

        // basic validation (MVP)
        if (displayName.Length < 3 || displayName.Length > 20)
            throw new Exception("Display name must be 3-20 characters");

        if (!System.Text.RegularExpressions.Regex.IsMatch(displayName, "^[a-zA-Z0-9 ]+$"))
            throw new Exception("Only letters, numbers and spaces allowed");

        var lower = displayName.ToLower();

        var bannedWords = new[] { "badword1", "badword2" };

        if (bannedWords.Any(w => lower.Contains(w)))
            throw new Exception("Display name not allowed");

        var user = await _context.Users.FindAsync(userId);

        if (user == null)
            throw new Exception("User not found");

        user.DisplayName = displayName;
        user.IsNameAutoGenerated = false;

        await _context.SaveChangesAsync();

        return new { user.DisplayName };
    }

    public async Task<object> GetLeaderboard()
    {
        // users allowed on leaderboard
        var allowedUserIds = await _context.Users
            .Where(u => u.Role != Roles.Admin)
            .Select(u => u.Id)
            .ToListAsync();

        // aggregate scores per user
        var data = await _context.QuizAttempts
            .Where(a =>
                a.CompletedAt != null &&
                allowedUserIds.Contains(a.UserId))
            .GroupBy(a => a.UserId)
            .Select(g => new
            {
                UserId = g.Key,
                TotalScore = g.Sum(a => a.Score),
                Attempts = g.Count()
            })
            .OrderByDescending(x => x.TotalScore)
            .Take(10)
            .ToListAsync();

        var userIds = data.Select(x => x.UserId).ToList();

        var users = await _context.Users
            .Where(u => userIds.Contains(u.Id))
            .ToDictionaryAsync(u => u.Id);

        var result = data
            .Select((x, index) => new
            {
                userId = x.UserId,
                rank = index + 1,
                displayName = users[x.UserId].DisplayName,
                totalScore = x.TotalScore,
                attempts = x.Attempts
            });

        return result;
    } 

    public async Task<object> GetUserStats(int userId)
    {
        var attempts = await _context.QuizAttempts
            .Include(a => a.Questions)
            .Where(a => a.UserId == userId && a.CompletedAt != null)
            .ToListAsync();

        if (!attempts.Any())
        {
            return new
            {
                totalAttempts = 0,
                totalScore = 0,
                averageScore = 0,
                bestScore = 0,
                averageAccuracy = 0
            };
        }

        var totalAttempts = attempts.Count;
        var totalScore = attempts.Sum(a => a.Score);
        var averageScore = Math.Round(attempts.Average(a => a.Score), 2);
        var bestScore = attempts.Max(a => a.Score);

        var allQuestions = attempts.SelectMany(a => a.Questions);

        var totalQuestions = allQuestions.Count();
        var correctAnswers = allQuestions.Count(q => q.Correct == true);

        var averageAccuracy = totalQuestions == 0
            ? 0
            : Math.Round((double)correctAnswers / totalQuestions * 100, 2);

        return new
        {
            totalAttempts,
            totalScore,
            averageScore,
            bestScore,
            averageAccuracy
        };
    }

